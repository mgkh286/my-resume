const languageButton = document.querySelector(".language-toggle");
const description = document.querySelector('meta[name="description"]');

function setLanguage(language) {
  const isArabic = language === "ar";
  const dictionary = translations[language];

  document.documentElement.lang = language;
  document.documentElement.dir = isArabic ? "rtl" : "ltr";
  document.title = isArabic
    ? "محمد خليفة | السيرة الذاتية"
    : "Mohamed Khalifa | Resume";
  description.content = isArabic
    ? "السيرة الذاتية لمحمد خليفة، مطور واجهات أمامية ومتخصص نظم معلومات جغرافية."
    : "The resume of Mohamed Khalifa, a front-end developer and GIS specialist.";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = dictionary[element.dataset.i18n];
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    element.alt = dictionary[element.dataset.i18nAlt];
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    element.setAttribute(
      "aria-label",
      dictionary[element.dataset.i18nAria],
    );
  });

  languageButton.textContent = isArabic ? "English" : "العربية";
  languageButton.setAttribute(
    "aria-label",
    isArabic ? "Switch to English" : "Switch to Arabic",
  );
}

languageButton.addEventListener("click", () => {
  setLanguage(document.documentElement.lang === "en" ? "ar" : "en");
});

setLanguage("en");
